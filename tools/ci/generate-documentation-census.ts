export const renderDocumentationCensus = (
    privateLinkTargets?: Readonly<Record<string, string>>,
): string => linkPrivateOwners(renderCensusText(), privateLinkTargets);

// The census lives among private planning documents. Its sentences cite
// them as [label](private:key), and a table beside the census maps each key
// to its target, so this tracked source names none of them. Without the
// table each citation keeps its label as plain text.
export const linkPrivateOwners = (
    text: string,
    targets: Readonly<Record<string, string>> | undefined,
): string =>
    text.replace(
        /\[([^\]]+)\]\(private:([a-z-]+)\)/gu,
        (_citation, label: string, key: string) => {
            if (targets === undefined) return label;
            const target = targets[key];
            if (target === undefined)
                throw new Error(`The census link table has no ${key}.`);
            return `[${label}](${target})`;
        },
    );

const normalizeCensusLine = (line: string): string =>
    line.startsWith('|')
        ? line
              .split('|')
              .map((cell) => cell.trim().replace(/^-{3,}$/u, '---'))
              .join('|')
        : line;

const normalizeCensusText = (text: string): string[] =>
    text.replace(/\r\n/g, '\n').split('\n').map(normalizeCensusLine);

export const findFirstCensusMismatch = (
    stored: string,
    rendered: string,
): number | undefined => {
    const storedLines = normalizeCensusText(stored);
    const renderedLines = normalizeCensusText(rendered);
    const length = Math.max(storedLines.length, renderedLines.length);
    for (let index = 0; index < length; index += 1) {
        if (storedLines[index] !== renderedLines[index]) return index + 1;
    }
    return undefined;
};

// The private link table, when present, lies beside the census.
const readPrivateLinkTargets = async (
    censusPath: string,
): Promise<Readonly<Record<string, string>> | undefined> => {
    try {
        return JSON.parse(
            await readFile(
                path.join(path.dirname(censusPath), 'census-links.json'),
                'utf8',
            ),
        ) as Record<string, string>;
    } catch (error) {
        if ((error as NodeJS.ErrnoException).code === 'ENOENT')
            return undefined;
        throw error;
    }
};

const usage =
    'Usage: generate-documentation-census.ts (--output <file> | --check <file>)';

const main = async (): Promise<void> => {
    const argumentsList = toolArguments(process.argv.slice(2));
    const [mode, target] = argumentsList;
    if (
        argumentsList.length !== 2 ||
        (mode !== '--output' && mode !== '--check') ||
        target === undefined
    )
        throw new Error(usage);
    const targetPath = path.resolve(target);
    const rendered = renderDocumentationCensus(
        await readPrivateLinkTargets(targetPath),
    );
    if (mode === '--output') {
        await writeFile(targetPath, rendered, 'utf8');
        process.stdout.write(
            `Wrote ${String(Buffer.byteLength(rendered))} bytes to ${targetPath}\n`,
        );
        return;
    }
    const stored = await readFile(targetPath, 'utf8');
    const mismatch = findFirstCensusMismatch(stored, rendered);
    if (mismatch !== undefined) {
        throw new Error(
            `The stored census is stale at line ${String(mismatch)}; regenerate it with --output.`,
        );
    }
    process.stdout.write('The stored census matches the models.\n');
};

if (import.meta.main) await main();
