use evaluation_target::{
    release::ReleaseContext,
    release_body::{ReleaseBodyVerifier, VerifiedReleaseBody},
};
use linked_release_proof::{ReleaseInputs, derive_bound, proof::prove, statement::PublicStatement};
use protocol_foundations::{
    Credential, Error,
    ballot_authentication::RetainedBallotOwner,
    release_signing::{RELEASE_BODY_HEADER_BYTES, ReleaseEnvelope},
    target_signing::TargetMessage,
};
use setup_witness::{contribution::common_share_polynomial, registration::RegistrationKey};
use std::sync::Arc;
use word_proof::one_shot::OneShotProof;

/// Private generation is reachable only from an actual verified target
/// certificate and the corresponding original participant/root context.
pub struct ReleaseWork {
    context: Arc<ReleaseContext>,
    owner: Arc<RetainedBallotOwner>,
}
impl ReleaseWork {
    pub fn new(
        owner: Arc<RetainedBallotOwner>,
        context: Arc<ReleaseContext>,
    ) -> Result<Self, Error> {
        let target = context.certificate().target();
        if owner.position() != context.position()
            || owner.poll() != &target.poll().identity()
            || owner.setup_identity() != &target.setup().identity()
        {
            return Err(Error::Context);
        }
        Ok(Self { context, owner })
    }
    /// Consumes this volatile operation. The worker must retain the exact
    /// target and the release seed first; restart replays that same
    /// operation from the seed.
    pub fn prove(
        self,
        key: &RegistrationKey,
        credential: &mut Credential,
    ) -> Result<(Arc<ReleaseContext>, PublicStatement, OneShotProof), Error> {
        if self.owner.position() != self.context.position()
            || key.public_key() != self.context.public_key()
        {
            return Err(Error::Context);
        }
        let target = self.context.certificate().target();
        let setup = target.setup();
        let message = TargetMessage::parse(target.body(), setup.profile().participants())?;
        credential.begin_release(&self.owner, setup.roster(), &message)?;
        // The key lends its secret only to the release's preparation and
        // proof, which leave it with the public statement and proof alone.
        let (statement, proof) = key
            .lend_secret(|secret| {
                let inputs = ReleaseInputs::new(
                    self.context.profile(),
                    common_share_polynomial(),
                    key.public_key().to_vec(),
                    self.context.encrypted_constant().to_vec(),
                    self.context.encrypted_linear().to_vec(),
                    self.context.target_linear().to_vec(),
                    secret,
                )
                .map_err(|_| Error::Crypto)?;
                let prepared =
                    derive_bound(inputs, *self.context.header()).map_err(|_| Error::Crypto)?;
                let role = self.context.proof_role().map_err(|_| Error::Context)?;
                Ok(prove(&role, prepared))
            })
            .map_err(|_| Error::Crypto)??;
        let expected = self
            .context
            .statement(&statement.polynomials[5])
            .map_err(|_| Error::Crypto)?;
        if statement.header != expected.header || statement.polynomials != expected.polynomials {
            return Err(Error::Context);
        }
        Ok((self.context, statement, proof))
    }
}

/// The largest slice of a release body that one call reads, imports or
/// verifies.
pub const RELEASE_CHUNK_BYTES: usize = 1 << 20;

fn verify_body(context: Arc<ReleaseContext>, body: &[u8]) -> Result<VerifiedReleaseBody, Error> {
    let header = body.get(..RELEASE_BODY_HEADER_BYTES).ok_or(Error::Shape)?;
    let mut verifier = ReleaseBodyVerifier::new(context, header).map_err(|_| Error::Crypto)?;
    for chunk in body[RELEASE_BODY_HEADER_BYTES..].chunks(RELEASE_CHUNK_BYTES) {
        verifier.push(chunk).map_err(|_| Error::Crypto)?;
    }
    verifier.finish().map_err(|_| Error::Crypto)
}

/// A release body and its envelope: generated by this instance, or imported
/// from the participant's records in slices, and in either case verified by
/// the release body verifier before it can be read or signed. A refused
/// slice or a failed verification closes the import for good.
pub struct ReleaseBody {
    body: Vec<u8>,
    envelope: ReleaseEnvelope,
    verified: Option<VerifiedReleaseBody>,
    import_closed: bool,
}
impl ReleaseBody {
    pub fn generated(context: Arc<ReleaseContext>, body: Vec<u8>) -> Result<Self, Error> {
        let verified = verify_body(context, &body)?;
        Ok(Self {
            body,
            envelope: verified.envelope(),
            verified: Some(verified),
            import_closed: false,
        })
    }
    pub fn importing(envelope: ReleaseEnvelope) -> Self {
        Self {
            body: Vec::with_capacity(envelope.body_length()),
            envelope,
            verified: None,
            import_closed: false,
        }
    }
    pub fn envelope(&self) -> &ReleaseEnvelope {
        &self.envelope
    }
    /// A slice of a verified body of at most one chunk.
    pub fn slice(&self, offset: usize, length: usize) -> Result<&[u8], Error> {
        if self.verified.is_none() || length == 0 || length > RELEASE_CHUNK_BYTES {
            return Err(Error::Context);
        }
        self.body
            .get(offset..offset.checked_add(length).ok_or(Error::Shape)?)
            .ok_or(Error::Shape)
    }
    pub fn push(&mut self, bytes: &[u8]) -> Result<(), Error> {
        if self.import_closed
            || self.verified.is_some()
            || bytes.is_empty()
            || bytes.len() > RELEASE_CHUNK_BYTES
            || bytes.len() > self.envelope.body_length() - self.body.len()
        {
            self.import_closed = true;
            return Err(Error::Shape);
        }
        self.body.extend(bytes);
        Ok(())
    }
    /// Verifies the complete imported body under the release context, which
    /// only the public verifier supplies, against the envelope it was opened
    /// with.
    pub fn finish(&mut self, context: Option<Arc<ReleaseContext>>) -> Result<(), Error> {
        if self.import_closed
            || self.verified.is_some()
            || self.body.len() != self.envelope.body_length()
        {
            self.import_closed = true;
            return Err(Error::Shape);
        }
        // Any failed verification permanently closes this volatile import.
        self.import_closed = true;
        let verified = verify_body(context.ok_or(Error::Context)?, &self.body)?;
        if verified.envelope().bytes() != self.envelope.bytes() {
            return Err(Error::Context);
        }
        self.verified = Some(verified);
        Ok(())
    }
    /// The verified envelope, when the input names it exactly.
    pub fn signable(&self, input: &[u8]) -> Result<ReleaseEnvelope, Error> {
        let envelope = self.verified.as_ref().ok_or(Error::Context)?.envelope();
        if input != envelope.bytes() {
            return Err(Error::Context);
        }
        Ok(envelope)
    }
}

